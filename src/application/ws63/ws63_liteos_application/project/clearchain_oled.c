static int oled_write(uint8_t control, const uint8_t *bytes, size_t length)
{
    int result = -1;

    if (bytes == NULL || length == 0U || clearchain_soft_i2c_lock() != 0) {
        return -1;
    }

    clearchain_soft_i2c_start();
    if (clearchain_soft_i2c_write_byte((uint8_t)(CLEARCHAIN_OLED_I2C_ADDRESS << 1U)) !=
            CLEARCHAIN_SOFT_I2C_ACK ||
        clearchain_soft_i2c_write_byte(control) != CLEARCHAIN_SOFT_I2C_ACK) {
        goto done;
    }
    for (size_t i = 0; i < length; i++) {
        if (clearchain_soft_i2c_write_byte(bytes[i]) != CLEARCHAIN_SOFT_I2C_ACK) {
            goto done;
        }
    }
    result = 0;

done:
    clearchain_soft_i2c_stop();
    clearchain_soft_i2c_unlock();
    return result;
}

static int oled_write_commands(const uint8_t *commands, size_t count)
{
    return oled_write(OLED_CONTROL_COMMAND, commands, count);
}

int oled_flush(void)
{
    static const uint8_t address_window[] = {
        0x21U, 0x00U, (uint8_t)(CLEARCHAIN_OLED_WIDTH - 1U),
        0x22U, 0x00U, (uint8_t)(CLEARCHAIN_OLED_PAGE_COUNT - 1U)
    };

    if (!g_oled_ready) {
        return -1;
    }
    if (oled_write_commands(address_window, sizeof(address_window)) != 0) {
        return -1;
    }
    return oled_write(OLED_CONTROL_DATA, g_oled_buffer, sizeof(g_oled_buffer));
}

int oled_init(void)
{
    static const uint8_t init_commands[] = {
        0xAEU, 0xD5U, 0x80U, 0xA8U, 0x3FU, 0xD3U, 0x00U, 0x40U,
        0x8DU, 0x14U, 0x20U, 0x00U, 0xA1U, 0xC8U, 0xDAU, 0x12U,
        0x81U, 0xCFU, 0xD9U, 0xF1U, 0xDBU, 0x30U, 0xA4U, 0xA6U
    };
    static const uint8_t display_on = 0xAFU;

    if (clearchain_soft_i2c_init() != 0) {
        return -1;
    }
    osal_msleep(20U);
    if (oled_write_commands(init_commands, sizeof(init_commands)) != 0) {
        return -1;
    }

    (void)memset(g_oled_buffer, 0, sizeof(g_oled_buffer));
    g_oled_ready = 1U;
    if (oled_flush() != 0 || oled_write_commands(&display_on, 1U) != 0) {
        g_oled_ready = 0U;
        return -1;
    }
    return 0;
}

int oled_clear(void)
{
    if (!g_oled_ready) {
        return -1;
    }
    (void)memset(g_oled_buffer, 0, sizeof(g_oled_buffer));
    return oled_flush();
}

int oled_display_on(void)
{
    static const uint8_t commands[] = { 0x8DU, 0x14U, 0xAFU };
    return g_oled_ready ? oled_write_commands(commands, sizeof(commands)) : -1;
}

int oled_display_off(void)
{
    static const uint8_t commands[] = { 0xAEU, 0x8DU, 0x10U };
    return g_oled_ready ? oled_write_commands(commands, sizeof(commands)) : -1;
}

int oled_set_pixel(uint8_t x, uint8_t y, uint8_t on)
{
    size_t index;
    uint8_t mask;

    if (x >= CLEARCHAIN_OLED_WIDTH || y >= CLEARCHAIN_OLED_HEIGHT) {
        return -1;
    }
    index = ((size_t)y / 8U) * CLEARCHAIN_OLED_WIDTH + x;
    mask = (uint8_t)(1U << (y & 7U));
    if (on) {
        g_oled_buffer[index] |= mask;
    } else {
        g_oled_buffer[index] &= (uint8_t)~mask;
    }
    return 0;
}

int oled_draw_char(uint8_t x, uint8_t y, char character)
{
    uint8_t font_index;

    if (character < ' ' || character > '~') {
        character = '?';
    }
    font_index = (uint8_t)(character - ' ');

    for (uint8_t column = 0; column < OLED_CHAR_WIDTH; column++) {
        uint8_t bits = column < 5U ? g_oled_font[font_index][column] : 0U;
        for (uint8_t row = 0; row < OLED_CHAR_HEIGHT; row++) {
            uint16_t pixel_x = (uint16_t)x + column;
            uint16_t pixel_y = (uint16_t)y + row;
            if (pixel_x < CLEARCHAIN_OLED_WIDTH && pixel_y < CLEARCHAIN_OLED_HEIGHT) {
                (void)oled_set_pixel((uint8_t)pixel_x, (uint8_t)pixel_y,
                                     (uint8_t)((bits >> row) & 1U));
            }
        }
    }
    return 0;
}

int oled_draw_string(uint8_t x, uint8_t y, const char *text)
{
    if (text == NULL || y >= CLEARCHAIN_OLED_HEIGHT) {
        return -1;
    }

    while (*text != '\0') {
        if (*text == '\n' || x > (CLEARCHAIN_OLED_WIDTH - OLED_CHAR_WIDTH)) {
            x = 0U;
            y = (uint8_t)(y + OLED_CHAR_HEIGHT);
            if (*text == '\n') {
                text++;
                continue;
            }
        }
        if (y > (CLEARCHAIN_OLED_HEIGHT - OLED_CHAR_HEIGHT)) {
            break;
        }
        (void)oled_draw_char(x, y, *text++);
        x = (uint8_t)(x + OLED_CHAR_WIDTH);
    }
    return 0;
}

int oled_draw_rect(uint8_t x, uint8_t y, uint8_t width, uint8_t height,
                   uint8_t filled)
{
    if (width == 0U || height == 0U || x >= CLEARCHAIN_OLED_WIDTH ||
        y >= CLEARCHAIN_OLED_HEIGHT ||
        (uint16_t)x + width > CLEARCHAIN_OLED_WIDTH ||
        (uint16_t)y + height > CLEARCHAIN_OLED_HEIGHT) {
        return -1;
    }

    for (uint8_t row = 0; row < height; row++) {
        for (uint8_t column = 0; column < width; column++) {
            if (filled || row == 0U || row == (uint8_t)(height - 1U) ||
                column == 0U || column == (uint8_t)(width - 1U)) {
                (void)oled_set_pixel((uint8_t)(x + column),
                                     (uint8_t)(y + row), 1U);
            }
        }
    }
    return 0;
}

int oled_draw_progress_bar(uint8_t x, uint8_t y, uint8_t width, uint8_t height,
                           uint8_t percent)
{
    uint8_t fill_width;

    if (width < 3U || height < 3U || percent > 100U ||
        oled_draw_rect(x, y, width, height, 0U) != 0) {
        return -1;
    }
    fill_width = (uint8_t)(((uint16_t)(width - 2U) * percent) / 100U);
    if (fill_width > 0U) {
        return oled_draw_rect((uint8_t)(x + 1U), (uint8_t)(y + 1U),
                              fill_width, (uint8_t)(height - 2U), 1U);
    }
    return 0;
}

int oled_test_page(void)
{
    if (!g_oled_ready) {
        return -1;
    }
    (void)memset(g_oled_buffer, 0, sizeof(g_oled_buffer));
    (void)oled_draw_string(0U, 0U, "ClearChain OLED");
    (void)oled_draw_string(0U, 16U, "SSD1315 128x64");
    (void)oled_draw_rect(0U, 31U, 128U, 12U, 0U);
    (void)oled_draw_progress_bar(4U, 48U, 120U, 10U, 60U);
    return oled_flush();
}
